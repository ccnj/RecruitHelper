// Package handinput 是**手的另一半**。
//
// 手被 Chrome 的沙箱切成了两半:插件那半跑在浏览器里,能爬 DOM、能读 clientX,
// 但发不出真实的系统输入;这半跑在脑进程里,能调 SendInput,但对页面一无所知。
// 两半合起来才是一只手。
//
// **它租住在脑的地址空间里,不是脑的能力。** 这条区分不是措辞洁癖:
//
//   - 业务层永远不知道有坐标这回事。脑→手的命令是意图级的(`chat.sendMessage`),
//     坐标从生到死都在手侧。
//   - 本包不 import 任何业务包,业务包也不 import 本包(门禁盯着,见 doc_test.go)。
//   - 坐标的方向是 手→本包 的请求/响应,与 脑→手 正好相反。
//
// # 分界:数据 / 过程
//
// **插件产出数据**(一份带时刻的坐标序列),**本包执行过程**(按时刻把它播出去)。
//
// 轨迹生成留在插件,不移植进 Go,决定性依据是上游打字线那条 LCG 跨语言不等价:
// `s*1103515245` 在 s 接近 2^31 时乘积超过 2^53,JS 的精度丢失是结果的一部分,
// Go 用精确整数照抄公式第一步就分叉。移植等于作废上游已有的判别器验收。
//
// 所以本包里**不许出现"生成"或"决定走哪条路径"**。一旦出现,分界就破了,
// 上游的引擎搬不回去、离线跑分也对不上真机跑出来的东西。
//
// # 与上游的关系
//
// 坐标层与搭车标定改写自 hiBoss `lab/engine/inject/{coord,piggyback}.go`
// (commit ef1b134)。与插件侧的 `osengine/vendor/` 不同,**这一侧是搬运加改写、
// 由我方接手维护**:它是确定性算术,正确性不依赖任何统计验收,而它必须接我方
// 自己的编排(没有上游那个标定页与 CLI)。
//
// 注释里的推导与反例是这批代码最值钱的部分,改动前先读完再动。
//
// # 有意没有搬过来的:哨兵探针
//
// 上游 `CanaryCSS` + `refineCalib` 会主动注入几个"最容易翻"的 CSS 坐标、
// 读回来核对整数映射,用来抓"残差很小但映射整体偏一格"那类病(上游 §30 事故)。
//
// 我方暂不搬,理由是**编排形态不同**:上游是播完整条轨迹再核对,我方每一次移动
// 都拿落点跟已知目标核对(编排层的落点判据),那道判据把"点不点得中"这一面盖住了。
// 剩下没盖住的是 1px 级的保真度——它只影响逐帧位移这个判定特征,也就是"像不像人",
// 按既定范围归 BOSS 阶段,不在本轮。
//
// 代价知情:在此之前,一个"残差小但整体偏一格"的标定不会被本包发现。
